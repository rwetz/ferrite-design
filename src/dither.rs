/// The 4×4 Bayer matrix. Thresholds are `(m + 0.5) / 16`.
pub const BAYER4: [[u8; 4]; 4] = [[0, 8, 2, 10], [12, 4, 14, 6], [3, 11, 1, 9], [15, 7, 13, 5]];

/// The threshold a level must exceed for cell `(x, y)` to be inked.
pub fn threshold(x: u32, y: u32) -> f32 {
    (BAYER4[(y % 4) as usize][(x % 4) as usize] as f32 + 0.5) / 16.0
}

/// Whether cell `(x, y)` is inked at `level`.
pub fn ink(x: u32, y: u32, level: f32) -> bool {
    level > threshold(x, y)
}

/// Side of the blue-noise tile, in cells. It repeats seamlessly.
pub const BLUE_NOISE_SIDE: u32 = 64;

/// A 64×64 void-and-cluster rank tile: every cell's rank 0..4096 as u16 LE.
/// Generated by `regenerate_blue_noise` in this file's tests; not third-party.
static BLUE_NOISE: &[u8] = include_bytes!("../assets/dither/blue-noise-64.bin");

/// The blue-noise threshold for cell `(x, y)`, like [`threshold`] for Bayer.
pub fn blue_noise_threshold(x: u32, y: u32) -> f32 {
    let i = (((y % BLUE_NOISE_SIDE) * BLUE_NOISE_SIDE + x % BLUE_NOISE_SIDE) * 2) as usize;
    (u16::from_le_bytes([BLUE_NOISE[i], BLUE_NOISE[i + 1]]) as f32 + 0.5) / 4096.0
}

/// How a level becomes ink.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum Pattern {
    /// 4×4 ordered dither: the cross-hatched Ferrite texture. Fields' default.
    Bayer4,
    /// Ordered dither over a blue-noise tile: an even, grid-free grain.
    /// Behaves exactly like `Bayer4` (stable, cacheable, steppable).
    BlueNoise,
    /// Atkinson error diffusion: crisp, high-contrast, blown highlights — the
    /// 1984 Mac look. Pictures' default. Never for texture or motion.
    Atkinson,
}

/// Atkinson's kernel: 1/8 of the error to each of six neighbours, so 2/8 is
/// thrown away. That loss is the look.
const ATKINSON: [(isize, usize); 6] = [(1, 0), (2, 0), (-1, 1), (0, 1), (1, 1), (0, 2)];

/// Which of `cols`×`rows` cells are inked, row-major, for per-cell `levels`.
pub fn mask(pattern: Pattern, cols: u32, rows: u32, levels: &[f32]) -> Vec<bool> {
    let (c, r) = (cols as usize, rows as usize);
    debug_assert_eq!(levels.len(), c * r);
    match pattern {
        Pattern::Bayer4 | Pattern::BlueNoise => {
            let t = if pattern == Pattern::Bayer4 { threshold } else { blue_noise_threshold };
            (0..r)
                .flat_map(|y| (0..c).map(move |x| (x, y)))
                .map(|(x, y)| levels[y * c + x] > t(x as u32, y as u32))
                .collect()
        }
        Pattern::Atkinson => {
            let mut level = levels.to_vec();
            let mut out = vec![false; c * r];
            for y in 0..r {
                for x in 0..c {
                    let i = y * c + x;
                    let on = level[i] > 0.5;
                    out[i] = on;
                    let err = (level[i] - if on { 1.0 } else { 0.0 }) / 8.0;
                    for (dx, dy) in ATKINSON {
                        let (nx, ny) = (x as isize + dx, y + dy);
                        if nx >= 0 && (nx as usize) < c && ny < r {
                            level[ny * c + nx as usize] += err;
                        }
                    }
                }
            }
            out
        }
    }
}

/// The levels Ferrite uses. Pick from these rather than inventing values so
/// textures match across apps; they map to the CP437 shades `░ ▒ ▓`.
pub mod level {
    pub const LIGHT: f32 = 0.25; // ░
    pub const MEDIUM: f32 = 0.5; // ▒
    pub const DARK: f32 = 0.75; // ▓
}

/// What level each point of an element gets. Coordinates are normalised:
/// `u` runs 0→1 left to right, `v` 0→1 top to bottom.
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum Field {
    /// Uniform level.
    Flat(f32),
    /// Linear ramp left → right.
    Horizontal { from: f32, to: f32 },
    /// Linear ramp top → bottom.
    Vertical { from: f32, to: f32 },
    /// Falloff from the centre (`center`) to the corners (`edge`).
    Radial { center: f32, edge: f32 },
}

impl Field {
    pub fn level(&self, u: f32, v: f32) -> f32 {
        match *self {
            Field::Flat(l) => l,
            Field::Horizontal { from, to } => from + (to - from) * u,
            Field::Vertical { from, to } => from + (to - from) * v,
            Field::Radial { center, edge } => {
                let (dx, dy) = (u - 0.5, v - 0.5);
                let d = ((dx * dx + dy * dy).sqrt() / std::f32::consts::FRAC_1_SQRT_2).min(1.0);
                center + (edge - center) * d
            }
        }
    }

    fn key(&self) -> [u32; 3] {
        match *self {
            Field::Flat(l) => [0, l.to_bits(), 0],
            Field::Horizontal { from, to } => [1, from.to_bits(), to.to_bits()],
            Field::Vertical { from, to } => [2, from.to_bits(), to.to_bits()],
            Field::Radial { center, edge } => [3, center.to_bits(), edge.to_bits()],
        }
    }
}

pub fn flat(level: f32) -> Field {
    Field::Flat(level)
}

pub fn horizontal(from: f32, to: f32) -> Field {
    Field::Horizontal { from, to }
}

pub fn vertical(from: f32, to: f32) -> Field {
    Field::Vertical { from, to }
}

pub fn radial(center: f32, edge: f32) -> Field {
    Field::Radial { center, edge }
}

/// A grayscale picture to dither: `w`×`h` levels, row-major, 0 = paper and
/// 255 = full ink. It is stretched over the element (bilinear), so size the
/// element to the picture's aspect.
#[derive(Debug, Clone)]
pub struct Picture {
    w: u32,
    h: u32,
    levels: Arc<[u8]>,
    id: u64,
}

impl Picture {
    pub fn new(w: u32, h: u32, levels: Vec<u8>) -> Self {
        assert_eq!(levels.len(), (w * h) as usize, "picture is w×h levels");
        let mut hasher = DefaultHasher::new();
        (w, h, &levels).hash(&mut hasher);
        Picture { w, h, levels: levels.into(), id: hasher.finish() }
    }

    /// Render `f(u, v) -> level` at `w`×`h`; `u`, `v` run 0→1.
    pub fn from_fn(w: u32, h: u32, f: impl Fn(f32, f32) -> f32) -> Self {
        let levels = (0..h)
            .flat_map(|y| (0..w).map(move |x| (x, y)))
            .map(|(x, y)| {
                let (u, v) = ((x as f32 + 0.5) / w as f32, (y as f32 + 0.5) / h as f32);
                (f(u, v).clamp(0.0, 1.0) * 255.0).round() as u8
            })
            .collect();
        Picture::new(w, h, levels)
    }

    fn level(&self, u: f32, v: f32) -> f32 {
        let fx = (u * self.w as f32 - 0.5).clamp(0.0, (self.w - 1) as f32);
        let fy = (v * self.h as f32 - 0.5).clamp(0.0, (self.h - 1) as f32);
        let (x0, y0) = (fx as u32, fy as u32);
        let (x1, y1) = ((x0 + 1).min(self.w - 1), (y0 + 1).min(self.h - 1));
        let at = |x: u32, y: u32| self.levels[(y * self.w + x) as usize] as f32 / 255.0;
        let (tx, ty) = (fx - x0 as f32, fy - y0 as f32);
        let top = at(x0, y0) + (at(x1, y0) - at(x0, y0)) * tx;
        let bottom = at(x0, y1) + (at(x1, y1) - at(x0, y1)) * tx;
        top + (bottom - top) * ty
    }
}

/// What a [`Dither`] draws: a synthetic [`Field`] or a [`Picture`].
#[derive(Debug, Clone)]
pub enum Source {
    Field(Field),
    Picture(Picture),
}

impl From<Field> for Source {
    fn from(field: Field) -> Self {
        Source::Field(field)
    }
}

impl From<Picture> for Source {
    fn from(picture: Picture) -> Self {
        Source::Picture(picture)
    }
}

impl Source {
    fn level(&self, u: f32, v: f32) -> f32 {
        match self {
            Source::Field(field) => field.level(u, v),
            Source::Picture(picture) => picture.level(u, v),
        }
    }

    fn key(&self) -> [u64; 2] {
        match self {
            Source::Field(field) => {
                let [tag, a, b] = field.key();
                [tag as u64, (a as u64) << 32 | b as u64]
            }
            Source::Picture(picture) => [u64::MAX, picture.id],
        }
    }

    fn default_pattern(&self) -> Pattern {
        match self {
            Source::Field(_) => Pattern::Bayer4,
            Source::Picture(_) => Pattern::Atkinson,
        }
    }
}

/// Rasterise `field` into a BGRA buffer `w`×`h` device pixels, with square
/// cells `cell` device pixels on a side, in the Bayer texture. Pure, so it is
/// testable.
pub fn raster(field: Field, w: u32, h: u32, cell: u32, ink_bgra: [u8; 4], paper_bgra: [u8; 4]) -> Vec<u8> {
    raster_source(&Source::Field(field), Pattern::Bayer4, w, h, cell, ink_bgra, paper_bgra)
}

/// [`raster`] for any source and pattern.
pub fn raster_source(source: &Source, pattern: Pattern, w: u32, h: u32, cell: u32, ink_bgra: [u8; 4], paper_bgra: [u8; 4]) -> Vec<u8> {
    let cell = cell.max(1);
    let (cols, rows) = (w.div_ceil(cell), h.div_ceil(cell));
    let levels: Vec<f32> = (0..rows)
        .flat_map(|row| (0..cols).map(move |col| (col, row)))
        .map(|(col, row)| {
            let u = ((col as f32 + 0.5) * cell as f32) / w.max(1) as f32;
            let v = ((row as f32 + 0.5) * cell as f32) / h.max(1) as f32;
            source.level(u, v)
        })
        .collect();
    let mask = mask(pattern, cols, rows, &levels);
    let mut out = vec![0u8; (w * h * 4) as usize];
    for y in 0..h {
        let row_mask = &mask[((y / cell) * cols) as usize..][..cols as usize];
        let line = &mut out[(y * w * 4) as usize..((y + 1) * w * 4) as usize];
        for (x, px) in line.chunks_exact_mut(4).enumerate() {
            px.copy_from_slice(if row_mask[x / cell as usize] { &ink_bgra } else { &paper_bgra });
        }
    }
    out
}

