    /// Void-and-cluster (Ulichney, 1993) on an `n`×`n` torus: ranks every
    /// cell 0..n² so that the first k cells, for any k, are spread as evenly
    /// as possible — blue noise. Deterministic for a given seed.
    fn void_and_cluster(n: usize, sigma: f32, seed: u64) -> Vec<u16> {
        let len = n * n;
        // Gaussian weight for each toroidal offset.
        let kernel: Vec<f32> = (0..len)
            .map(|i| {
                let (dx, dy) = (i % n, i / n);
                let (x, y) = (dx.min(n - dx) as f32, dy.min(n - dy) as f32);
                (-(x * x + y * y) / (2.0 * sigma * sigma)).exp()
            })
            .collect();
        let toggle = |on: &mut [bool], energy: &mut [f32], i: usize, set: bool| {
            on[i] = set;
            let sign = if set { 1.0 } else { -1.0 };
            let (ix, iy) = (i % n, i / n);
            for y in 0..n {
                for x in 0..n {
                    energy[y * n + x] += sign * kernel[((y + n - iy) % n) * n + (x + n - ix) % n];
                }
            }
        };
        let tightest = |on: &[bool], energy: &[f32]| (0..len).filter(|&i| on[i]).max_by(|&a, &b| energy[a].total_cmp(&energy[b])).unwrap();
        let largest_void = |on: &[bool], energy: &[f32]| (0..len).filter(|&i| !on[i]).min_by(|&a, &b| energy[a].total_cmp(&energy[b])).unwrap();

        let (mut on, mut energy) = (vec![false; len], vec![0.0f32; len]);
        let mut state = seed;
        let ones = len / 10;
        let mut placed = 0;
        while placed < ones {
            state ^= state << 13;
            state ^= state >> 7;
            state ^= state << 17;
            let i = (state % len as u64) as usize;
            if !on[i] {
                toggle(&mut on, &mut energy, i, true);
                placed += 1;
            }
        }
        // Relax the random seed: move the tightest point to the largest void
        // until that is a no-op.
        loop {
            let cluster = tightest(&on, &energy);
            toggle(&mut on, &mut energy, cluster, false);
            let void = largest_void(&on, &energy);
            toggle(&mut on, &mut energy, void, true);
            if void == cluster {
                break;
            }
        }
        let mut rank = vec![0u16; len];
        let (proto_on, proto_energy) = (on.clone(), energy.clone());
        for r in (0..ones).rev() {
            let cluster = tightest(&on, &energy);
            toggle(&mut on, &mut energy, cluster, false);
            rank[cluster] = r as u16;
        }
        // Filling the largest void is also the tightest cluster of the
        // inverted pattern, so this one loop covers both upper phases.
        let (mut on, mut energy) = (proto_on, proto_energy);
        for r in ones..len {
            let void = largest_void(&on, &energy);
            toggle(&mut on, &mut energy, void, true);
            rank[void] = r as u16;
        }
        rank
    }

