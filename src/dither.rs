    #[test]
    fn blue_noise_is_even_at_every_level() {
        // Blue noise has no clumps or holes: at each level every 8×8 window
        // holds close to its share of ink. A white-noise tile fails this.
        let side = BLUE_NOISE_SIDE;
        for level in [level::LIGHT, level::MEDIUM, level::DARK] {
            let expected = level * 64.0;
            for wy in (0..side).step_by(8) {
                for wx in (0..side).step_by(8) {
                    let n = (0..64).filter(|i| level > blue_noise_threshold(wx + i % 8, wy + i / 8)).count() as f32;
                    assert!((n - expected).abs() <= 8.0, "window ({wx},{wy}) at {level}: {n} vs {expected}");
                }
            }
        }
    }

    #[test]
    fn ordered_patterns_ink_the_exact_share() {
        let side = BLUE_NOISE_SIDE;
        let levels = vec![level::LIGHT; (side * side) as usize];
        let inked = mask(Pattern::BlueNoise, side, side, &levels).iter().filter(|&&b| b).count();
        assert_eq!(inked, (side * side / 4) as usize);
    }

    #[test]
    fn atkinson_expands_contrast_and_saturates() {
        // Atkinson drops 2/8 of the error, so tones move away from the middle:
        // a light field inks less than its level, a dark one more. That is
        // the look, not a bug — but it must stay ordered and bounded.
        let (c, r) = (64, 64);
        let share = |level: f32| {
            let inked = mask(Pattern::Atkinson, c, r, &vec![level; (c * r) as usize]).iter().filter(|&&b| b).count();
            inked as f32 / (c * r) as f32
        };
        let (light, medium, dark) = (share(level::LIGHT), share(level::MEDIUM), share(level::DARK));
        assert!(light < level::LIGHT && light > level::LIGHT - 0.12, "light {light}");
        assert!(dark > level::DARK && dark < level::DARK + 0.12, "dark {dark}");
        assert!((medium - 0.5).abs() < 0.06, "medium {medium}");
        assert_eq!(share(0.0), 0.0);
        assert_eq!(share(1.0), 1.0);
    }

    #[test]
    fn pictures_raster_in_every_pattern() {
        let picture = Picture::from_fn(16, 9, |u, v| u * v);
        for pattern in [Pattern::Bayer4, Pattern::BlueNoise, Pattern::Atkinson] {
            let buf = raster_source(&picture.clone().into(), pattern, 37, 21, 3, [9; 4], [0; 4]);
            assert_eq!(buf.len(), 37 * 21 * 4);
        }
    }
