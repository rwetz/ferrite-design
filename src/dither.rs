/// A dithered fill. Size it like any element (`.size_full()`, `.h(px(16.))`).
#[derive(IntoElement)]
pub struct Dither {
    source: Source,
    pattern: Option<Pattern>,
    ink: Option<Hsla>,
    paper: Option<Hsla>,
    cell: u32,
    style: StyleRefinement,
}

/// Start a dither over a [`Field`] or a [`Picture`]. Ink defaults to the
/// palette's `line_strong`.
pub fn dither(source: impl Into<Source>) -> Dither {
    Dither { source: source.into(), pattern: None, ink: None, paper: None, cell: 2, style: StyleRefinement::default() }
}

impl Dither {
    /// The color of inked cells.
    pub fn ink(mut self, color: Hsla) -> Self {
        self.ink = Some(color);
        self
    }

    /// Fill uninked cells too (default: transparent).
    pub fn paper(mut self, color: Hsla) -> Self {
        self.paper = Some(color);
        self
    }

    /// How levels become ink. Defaults: `Bayer4` for fields, `Atkinson` for
    /// pictures.
    pub fn pattern(mut self, pattern: Pattern) -> Self {
        self.pattern = Some(pattern);
        self
    }

    /// Cell edge in **device** pixels. 1 = finest, 2 = default, 3–4 = chunky.
    pub fn cell(mut self, device_px: u32) -> Self {
        self.cell = device_px.max(1);
        self
    }
}

impl Styled for Dither {
    fn style(&mut self) -> &mut StyleRefinement {
        &mut self.style
    }
}

/// Larger than any sane element; guards against a runaway layout asking for
/// a gigapixel texture.
const MAX_SIDE: u32 = 8192;

/// Paint `field` over `bounds` from inside another element's paint — the
/// [`Dither`] element's own path (device-snapped, cached, one quad). Charts
/// use it under a content mask to dither an area under a line: the pattern
/// stays anchored to `bounds`, so clipped pieces line up.
pub(crate) fn paint_field(field: Field, bounds: Bounds<Pixels>, ink: Hsla, window: &mut Window) {
    let sf = window.scale_factor();
    let ox = (f32::from(bounds.origin.x) * sf).round();
    let oy = (f32::from(bounds.origin.y) * sf).round();
    let w = ((f32::from(bounds.size.width) * sf).round() as u32).min(MAX_SIDE);
    let h = ((f32::from(bounds.size.height) * sf).round() as u32).min(MAX_SIDE);
    if w == 0 || h == 0 {
        return;
    }
    let (ink, paper, cell, pattern) = (bgra(ink), [0, 0, 0, 0], 2, Pattern::Bayer4);
    let source = Source::Field(field);
    let key = raster::Key::Dither { source: source.key(), pattern, w, h, cell, ink, paper };
    let image = raster::image(key, window, || (w, h, raster_source(&source, pattern, w, h, cell, ink, paper)));
    raster::paint(image, ox / sf, oy / sf, w, h, window);
}

impl RenderOnce for Dither {
    fn render(self, _window: &mut Window, cx: &mut App) -> impl IntoElement {
        let ink_color = self
            .ink
            .unwrap_or_else(|| crate::tokens::hsla(crate::theme::palette(cx).line_strong));
        let ink = bgra(ink_color);
        let paper = self.paper.map(bgra).unwrap_or([0, 0, 0, 0]);
        let pattern = self.pattern.unwrap_or_else(|| self.source.default_pattern());
        let source = self.source;
        let cell = self.cell;

        let mut element = canvas(
            |_, _, _| {},
            move |bounds: Bounds<Pixels>, _, window: &mut Window, _cx| {
                let sf = window.scale_factor();
                // Snap to the device grid so image pixels map 1:1 onto
                // screen pixels (no resampling blur).
                let ox = (f32::from(bounds.origin.x) * sf).round();
                let oy = (f32::from(bounds.origin.y) * sf).round();
                let w = ((f32::from(bounds.size.width) * sf).round() as u32).min(MAX_SIDE);
                let h = ((f32::from(bounds.size.height) * sf).round() as u32).min(MAX_SIDE);
                if w == 0 || h == 0 {
                    return;
                }
                let key = raster::Key::Dither { source: source.key(), pattern, w, h, cell, ink, paper };
                let image = raster::image(key, window, || (w, h, raster_source(&source, pattern, w, h, cell, ink, paper)));
                raster::paint(image, ox / sf, oy / sf, w, h, window);
            },
        );
        *element.style() = self.style;
        element
    }
}

