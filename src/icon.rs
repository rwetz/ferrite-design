//! Ferrite's pixel icons.
//!
//! Icons are 16×16 one-bit bitmaps drawn on the display font's grid with the
//! display font's stroke: 2-pixel stems, content inside rows/cols 1–14,
//! centred on the cell. They are rasterised at a whole multiple of their
//! pixel size — the same multiple `fonts::display_size` picks, so a 16px icon
//! next to `Scale::X1` text shares its pixel grid — cached, and painted as a
//! single textured quad.
//!
//! Why bitmaps and not glyphs: the display face only covers CP437/WGL4, and
//! anything outside it (`↻ ▶ ▸ ⚙ …`) silently falls back to a system font
//! with the wrong weight, size and baseline. Icons never fall back.
//!
//! Adding one: draw it in 16 rows of `#`/`.` following the rules above (see
//! the art comments), encode each row as a `u16` with column 0 in bit 15,
//! and add it to [`Icon`], [`Icon::ALL`] and the components showcase.

